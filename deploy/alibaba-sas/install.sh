#!/usr/bin/env bash
#
# Alibaba Cloud Simple Application Server - Docker install for tindahan-dev.novastack-inc.online
#
# Isolated from the other apps on the shared Novastack SAS:
#   Install dir:  /opt/fluent-tindahan   (.env and backups/ survive redeploys)
#   Compose name: fluent-tindahan        (containers fluent-tindahan-{db,api,web})
#   HTTP port:    127.0.0.1:8089         (loopback only; public traffic comes through Caddy)
#
set -euo pipefail

INSTALL_DIR="/opt/fluent-tindahan"
DOMAIN="tindahan-dev.novastack-inc.online"
HTTP_PORT="8089"
PROJECT_NAME="fluent-tindahan"
SKIP_SETUP=false
CONFIGURE_PROXY=true
MODIFY_DOCKER_CADDY=false
DEPLOY_ARGS=()

EDGE_NETWORK="novastack-edge"
CADDY_SITES_DIR="/opt/novastack-caddy/sites"
CADDYFILE="/etc/caddy/Caddyfile"

log() { printf '[sas-install] %s\n' "$*"; }
fail() { log "ERROR: $*"; exit 1; }

usage() {
  cat <<'EOF'
Alibaba SAS installer - isolated Docker deployment of Fluent Tindahan.

Usage:
  sudo bash deploy/alibaba-sas/install.sh [options]

Options:
  --dir PATH             Install directory (default: /opt/fluent-tindahan)
  --domain HOST          Public domain (default: tindahan-dev.novastack-inc.online)
  --port PORT            Loopback HTTP port (default: 8089)
  --name NAME            Docker Compose project name (default: fluent-tindahan)
  --skip-setup           Skip the Docker bootstrap check
  --no-proxy             Do not add the domain to Caddy/nginx
  --modify-docker-caddy  Allow appending to another project's Caddyfile if the shared sites dir is not mounted
  --no-backup            Skip the pre-deploy pg_dump snapshot
  --help                 Show this help
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dir) INSTALL_DIR="${2:-}"; shift 2 ;;
    --domain) DOMAIN="${2:-}"; shift 2 ;;
    --port) HTTP_PORT="${2:-}"; shift 2 ;;
    --name) PROJECT_NAME="${2:-}"; shift 2 ;;
    --skip-setup) SKIP_SETUP=true; shift ;;
    --no-proxy) CONFIGURE_PROXY=false; shift ;;
    --modify-docker-caddy) MODIFY_DOCKER_CADDY=true; shift ;;
    --no-backup) DEPLOY_ARGS+=(--no-backup); shift ;;
    -h|--help) usage; exit 0 ;;
    *) fail "Unknown option: $1" ;;
  esac
done

[[ "${EUID:-0}" -eq 0 ]] || fail "Run as root: sudo bash $0"

APP_DIR="${INSTALL_DIR}"
[[ -f "${APP_DIR}/docker-compose.yml" ]] || fail "Missing ${APP_DIR}/docker-compose.yml. Deploy with deploy-alibaba-sas.cmd first."
cd "${APP_DIR}"

if [[ "${SKIP_SETUP}" != "true" ]]; then
  bash "${APP_DIR}/deploy/alibaba-sas/setup-server.sh"
fi

random_secret() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 "$1" | tr -d '\n/=+'
  else
    head -c "$1" /dev/urandom | base64 | tr -d '\n/=+'
  fi
}

ENV_FILE="${APP_DIR}/.env"
SECRETS_FILE="${APP_DIR}/deploy/alibaba-sas/secrets.env"

env_value() { [[ -f "$2" ]] && sed -n "s/^$1=//p" "$2" | tail -n 1 | tr -d '\r'; return 0; }

# Rewrites KEY=VALUE without sed so secrets containing |, & or \ survive. Keeps file permissions.
set_env_value() {
  local key="$1" value="$2" tmp
  tmp="$(mktemp)"
  grep -v "^${key}=" "${ENV_FILE}" > "${tmp}" || true
  printf '%s=%s\n' "${key}" "${value}" >> "${tmp}"
  cat "${tmp}" > "${ENV_FILE}"
  rm -f "${tmp}"
}

if [[ ! -f "${ENV_FILE}" ]]; then
  if docker volume inspect "${PROJECT_NAME}_pgdata" >/dev/null 2>&1; then
    fail "Database volume ${PROJECT_NAME}_pgdata exists but ${ENV_FILE} is missing. Restore the .env (POSTGRES_PASSWORD must match the existing database) before deploying."
  fi

  ( umask 077
    cat > "${ENV_FILE}" <<EOF
# Generated by deploy/alibaba-sas/install.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
COMPOSE_PROJECT_NAME=${PROJECT_NAME}
APP_URL=https://${DOMAIN}
HOST_HTTP_PORT=${HTTP_PORT}
ASPNETCORE_ENVIRONMENT=Production
POSTGRES_DB=fluent_tindahan
POSTGRES_USER=fluent
POSTGRES_PASSWORD=$(random_secret 24)
FIREBASE_PROJECT_ID=fluent-tindahan-dev
DEMO_MODE=false
ALLOW_DEMO_MODE_IN_PRODUCTION=false
JWT_SECRET_KEY=$(random_secret 48)
PAYMONGO_SECRET_KEY=
PAYMONGO_WEBHOOK_SECRET=
PAYMONGO_FRONTEND_ORIGIN=https://${DOMAIN}
EOF
  )
  log "Created ${ENV_FILE}"
else
  log "Using existing ${ENV_FILE}"
  sed -i 's/\r$//' "${ENV_FILE}"
fi
chmod 600 "${ENV_FILE}"

# Install args always win over leftovers in the server .env.
set_env_value COMPOSE_PROJECT_NAME "${PROJECT_NAME}"
set_env_value HOST_HTTP_PORT "${HTTP_PORT}"
set_env_value APP_URL "https://${DOMAIN}"
[[ -n "$(env_value PAYMONGO_FRONTEND_ORIGIN "${ENV_FILE}")" ]] || set_env_value PAYMONGO_FRONTEND_ORIGIN "https://${DOMAIN}"
[[ -n "$(env_value DEMO_MODE "${ENV_FILE}")" ]] || set_env_value DEMO_MODE "false"

# Ensure a unique JWT_SECRET_KEY exists; generate a new secret if missing or set to the burned repo key
current_jwt="$(env_value JWT_SECRET_KEY "${ENV_FILE}")"
if [[ -z "${current_jwt}" || "${current_jwt}" == "FluentTindahan_SuperSecretSigningKey_Minimum32Chars_DevKey!" ]]; then
  set_env_value JWT_SECRET_KEY "$(random_secret 48)"
  log "Generated new unique JWT_SECRET_KEY (committed repo key was burned)"
fi

# Optional secrets pushed from the developer machine (deploy/alibaba-sas/secrets.env, gitignored).
# POSTGRES_PASSWORD is deliberately not accepted: changing it would lock the API out of the existing database.
if [[ -f "${SECRETS_FILE}" ]]; then
  sed -i 's/\r$//' "${SECRETS_FILE}"
  for key in JWT_SECRET_KEY PAYMONGO_SECRET_KEY PAYMONGO_WEBHOOK_SECRET PAYMONGO_FRONTEND_ORIGIN FIREBASE_PROJECT_ID ASPNETCORE_ENVIRONMENT DEMO_MODE DemoMode ALLOW_DEMO_MODE_IN_PRODUCTION AllowDemoModeInProduction GOOGLE_CLIENT_ID; do
    value="$(env_value "${key}" "${SECRETS_FILE}")"
    if [[ -n "${value}" ]]; then
      set_env_value "${key}" "${value}"
      log "Updated ${key} from secrets.env"
    fi
  done
  rm -f "${SECRETS_FILE}"
fi

log "Deploying Docker stack (project: ${PROJECT_NAME}, port: 127.0.0.1:${HTTP_PORT})..."
bash "${APP_DIR}/deploy/alibaba-sas/deploy.sh" "${DEPLOY_ARGS[@]+"${DEPLOY_ARGS[@]}"}"

# --- Reverse proxy (ports 80/443 on this server belong to the Lying-in Caddy container) ---

caddy_site_block() {
  printf '# %s - Fluent Tindahan (%s), added by install.sh\n%s {\n    encode gzip\n    reverse_proxy %s\n}\n' \
    "${DOMAIN}" "${PROJECT_NAME}" "${DOMAIN}" "$1"
}

# True if a Caddyfile line starts a site block for exactly this host (not a sibling *.novastack-inc.online).
caddy_has_site() {
  local host_re="${1//./\\.}"
  grep -qsE "^[[:space:]]*(https?://)?${host_re}(:[0-9]+)?([[:space:]]*[{,]|[[:space:]]*$)" "${@:2}"
}

caddy_container_mount() {
  docker inspect -f "{{range .Mounts}}{{if eq .Destination \"$2\"}}{{.Source}}{{end}}{{end}}" "$1"
}

caddy_container_reload() {
  docker exec "$1" caddy validate --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1 \
    && docker exec "$1" caddy reload --config /etc/caddy/Caddyfile --adapter caddyfile >/dev/null 2>&1
}

# Caddy in another project's container reaches the app over the shared novastack-edge network,
# so the upstream is the web container name, not 127.0.0.1 (that would be the Caddy container itself).
configure_docker_caddy() {
  local container="$1"
  local upstream="${PROJECT_NAME}-web:80"

  if ! docker inspect -f '{{json .NetworkSettings.Networks}}' "${container}" | grep -qF "\"${EDGE_NETWORK}\""; then
    docker network connect "${EDGE_NETWORK}" "${container}" \
      && log "Connected ${container} to ${EDGE_NETWORK}." \
      || { log "WARNING: could not connect ${container} to ${EDGE_NETWORK}."; return 0; }
  fi

  if [[ -n "$(caddy_container_mount "${container}" /etc/caddy/sites)" ]]; then
    mkdir -p "${CADDY_SITES_DIR}"
    local site_file="${CADDY_SITES_DIR}/${DOMAIN}.caddy"
    local previous=""
    [[ -f "${site_file}" ]] && previous="$(cat "${site_file}")"
    caddy_site_block "${upstream}" > "${site_file}"
    if caddy_container_reload "${container}"; then
      log "Caddy (${container}): https://${DOMAIN} -> ${upstream} via ${site_file} (certificate is issued automatically)"
    else
      if [[ -n "${previous}" ]]; then printf '%s\n' "${previous}" > "${site_file}"; else rm -f "${site_file}"; fi
      caddy_container_reload "${container}" || true
      log "WARNING: ${container} rejected ${site_file}; restored the previous state."
    fi
    return 0
  fi

  local src
  src="$(caddy_container_mount "${container}" /etc/caddy/Caddyfile)"
  if [[ -z "${src}" ]]; then
    src="$(caddy_container_mount "${container}" /etc/caddy)"
    [[ -n "${src}" ]] && src="${src}/Caddyfile"
  fi
  if [[ -z "${src}" || ! -f "${src}" ]]; then
    log "Caddy container ${container} has no host-mounted Caddyfile. Add this site manually:"
    caddy_site_block "${upstream}"
    return 0
  fi
  if caddy_has_site "${DOMAIN}" "${src}"; then
    log "${container} already serves ${DOMAIN} (${src})."
    return 0
  fi
  if [[ "${MODIFY_DOCKER_CADDY}" != "true" ]]; then
    log "${container} does not import ${CADDY_SITES_DIR}; its Caddyfile (${src}) was left untouched."
    log "Re-run with -ModifyDockerCaddy to append the site there, or add it manually:"
    caddy_site_block "${upstream}"
    return 0
  fi

  local backup="${src}.bak.$(date +%Y%m%d%H%M%S)"
  cp "${src}" "${backup}"
  { printf '\n'; caddy_site_block "${upstream}"; } >> "${src}"
  if ! caddy_container_reload "${container}"; then
    cat "${backup}" > "${src}"
    caddy_container_reload "${container}" || true
    log "WARNING: ${container} rejected the new site; restored ${src}."
    return 0
  fi
  log "Caddy (${container}): https://${DOMAIN} -> ${upstream} (backup ${backup})"
}

configure_host_caddy() {
  local files=() f
  while IFS= read -r -d '' f; do files+=("${f}"); done \
    < <(find "$(dirname "${CADDYFILE}")" -type f ! -name '*.bak.*' -print0 2>/dev/null)
  if (( ${#files[@]} )) && caddy_has_site "${DOMAIN}" "${files[@]}"; then
    log "Host Caddy already has a site for ${DOMAIN}; leaving it unchanged."
    return 0
  fi
  local backup="${CADDYFILE}.bak.$(date +%Y%m%d%H%M%S)"
  cp "${CADDYFILE}" "${backup}"
  { printf '\n'; caddy_site_block "127.0.0.1:${HTTP_PORT}"; } >> "${CADDYFILE}"
  if ! caddy validate --config "${CADDYFILE}" --adapter caddyfile >/dev/null 2>&1 || ! systemctl reload caddy; then
    cp "${backup}" "${CADDYFILE}"
    systemctl reload caddy || true
    log "WARNING: host Caddy rejected the new site; restored ${backup}."
    return 0
  fi
  log "Host Caddy: https://${DOMAIN} -> 127.0.0.1:${HTTP_PORT} (backup ${backup})"
}

configure_host_nginx() {
  local conf="/etc/nginx/conf.d/${DOMAIN}.conf"
  local template="${APP_DIR}/deploy/alibaba-sas/nginx-tindahan.conf.example"
  if [[ -f "${conf}" ]]; then
    log "Host nginx site exists: ${conf}"
  elif grep -rqsF --exclude="*.example" "server_name ${DOMAIN}" /etc/nginx; then
    log "Another nginx config already serves ${DOMAIN}; leaving it unchanged."
  else
    sed -e "s/tindahan-dev\.novastack-inc\.online/${DOMAIN}/g" -e "s/127\.0\.0\.1:8089/127.0.0.1:${HTTP_PORT}/" \
      "${template}" > "${conf}"
    if ! nginx -t >/dev/null 2>&1 || ! systemctl reload nginx; then
      rm -f "${conf}"
      log "WARNING: nginx rejected the new site; removed ${conf}."
      return 0
    fi
    log "Host nginx: http://${DOMAIN} -> 127.0.0.1:${HTTP_PORT} (${conf})"
  fi

  if [[ -d "/etc/letsencrypt/live/${DOMAIN}" ]]; then
    log "TLS certificate present for ${DOMAIN}."
  elif ! command -v certbot >/dev/null 2>&1; then
    log "certbot not installed. For HTTPS: install certbot + python3-certbot-nginx, then certbot --nginx -d ${DOMAIN} --redirect"
  elif ! getent ahostsv4 "${DOMAIN}" >/dev/null 2>&1; then
    log "DNS for ${DOMAIN} does not resolve yet. Add the A record, then redeploy."
  else
    certbot --nginx -d "${DOMAIN}" --redirect --non-interactive --agree-tos --register-unsafely-without-email \
      || log "WARNING: certbot failed. Check DNS and TCP 80, then run: certbot --nginx -d ${DOMAIN} --redirect"
  fi
}

configure_reverse_proxy() {
  [[ "${CONFIGURE_PROXY}" == "true" ]] || { log "Proxy setup skipped (--no-proxy)."; return 0; }

  if command -v caddy >/dev/null 2>&1 && systemctl is-active --quiet caddy 2>/dev/null && [[ -f "${CADDYFILE}" ]]; then
    configure_host_caddy
    return 0
  fi
  if command -v nginx >/dev/null 2>&1 && systemctl is-active --quiet nginx 2>/dev/null && [[ -d /etc/nginx/conf.d ]]; then
    configure_host_nginx
    return 0
  fi
  local caddy_container
  caddy_container="$(docker ps --format '{{.Names}} {{.Image}} {{.Ports}}' 2>/dev/null | awk '$2 ~ /caddy/ && /:(80|443)->/ {print $1; exit}' || true)"
  if [[ -n "${caddy_container}" ]]; then
    configure_docker_caddy "${caddy_container}"
    return 0
  fi
  log "No Caddy or nginx found on ports 80/443. Proxy ${DOMAIN} -> 127.0.0.1:${HTTP_PORT} manually."
}

configure_reverse_proxy || log "WARNING: reverse proxy setup failed; the app is still running on 127.0.0.1:${HTTP_PORT}."

if ! getent ahostsv4 "${DOMAIN}" >/dev/null 2>&1; then
  log "NOTE: ${DOMAIN} does not resolve yet. Add the DNS A record; Caddy issues the certificate once it does."
fi

log ""
log "============================================"
log " Fluent Tindahan deployed on SAS"
log "============================================"
log " Install:  ${APP_DIR}"
log " Project:  ${PROJECT_NAME}"
log " Domain:   https://${DOMAIN}"
log " Local:    http://127.0.0.1:${HTTP_PORT}/api/health"
